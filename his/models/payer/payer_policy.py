class PayerPolicy(models.Model):
    _name = "his.payer_policy"
    _inherit = "mail.thread"
    _description = "Payer Policy Records"
    _rec_name = "policy_number"

    full_name = fields.Char(string="Full Name", required=True)
    passport_serial = fields.Char(string="Passport Serial")
    phone_number = fields.Char(string="Phone Number")
    pinfl = fields.Char(string="PINFL")
    birth_date = fields.Date(string="Birth Date")
    gender = fields.Selection(
        [
            ("male", "Male"),
            ("female", "Female"),
        ],
        string="Gender",
        default="male",
    )
    contract_id = fields.Many2one("his.payer_contract")
    payer_company_id = fields.Many2one(
        "his.payer_company", required=True, tracking=True
    )
    patient_id = fields.Many2one("his.patient", tracking=True)
    policy_number = fields.Char(string="Policy Number", required=True, tracking=True)
    policy_amount = fields.Float(string="Policy Amount", tracking=True)
    from_date = fields.Date(
        string="From Date", required=True, default=fields.Date.today
    )
    to_date = fields.Date(
        string="To Date",
        required=True,
        default=lambda self: fields.Date.today() + timedelta(days=30),
        tracking=True,
    )
    is_active = fields.Boolean(string="Active", default=True, tracking=True)
    template_id = fields.Many2one("his.payer_template")
    template_domain = fields.Binary(compute="_compute_template_domain")
    is_readonly = fields.Boolean(string="Readonly", default=False)
    payer_policy_limit_ids = fields.One2many(
        "his.payer_policy_limit", "policy_id", string="Policy Limits", tracking=True
    )
    used_amount = fields.Float(
        string="Used Amount", compute="_compute_used_amount", store=False
    )
    balance = fields.Float(
        string="Balance", compute="_compute_used_amount", store=False
    )
    is_autogenerated = fields.Boolean(string="Autogenerated")

    _sql_constraints = [
        (
            "unique_policy_number_per_company",
            "unique(policy_number, payer_company_id)",
            "The policy number must be unique per payer branch.",
        )
    ]

    def _compute_used_amount(self):
        """Ishlatilgan summani read_group orqali hisoblash"""
        # TODO limit faqat bitta vizit uchun qulanilgani uchun bu logika to'g'ri ishlamaydi
        for record in self:
            result = self.env["sale.order.line"].read_group(
                domain=[("payer_policy", "=", record.id), ("state", "=", "sale")],
                fields=["coverage_amount:sum"],
                groupby=[],
            )
            record.used_amount = result[0]["coverage_amount"] if result else 0.0
            record.balance = record.policy_amount - record.used_amount

    @api.model
    def default_get(self, fields_list):
        defaults = super(PayerPolicy, self).default_get(fields_list)
        active_id = self.env.context.get("active_id", False)
        payer_company_id = self.env.context.get("payer_company_id", False)
        if self.env.context.get("active_model") == "his.patient_visit":
            patient_visit = self.env["his.patient_visit"].browse(active_id)
            defaults.update(
                {
                    "patient_id": patient_visit.patient_id.id,
                    "full_name": patient_visit.patient_id.full_name,
                    "birth_date": patient_visit.patient_id.date,
                    "pinfl": patient_visit.patient_id.pinfl,
                    "phone_number": patient_visit.patient_id.phone_number,
                    "passport_serial": patient_visit.patient_id.passport_serial,
                    "payer_company_id": payer_company_id,
                    "is_readonly": True,
                }
            )
        return defaults

